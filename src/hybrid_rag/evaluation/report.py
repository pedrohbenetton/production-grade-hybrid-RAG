"""Benchmark report: summary statistics, Markdown table and chart."""

from __future__ import annotations

from pathlib import Path

import numpy as np
from pydantic import BaseModel

from hybrid_rag.evaluation.metrics import METRICS, evaluate_run
from hybrid_rag.evaluation.runner import BenchmarkResult
from hybrid_rag.evaluation.stats import bootstrap_ci, paired_bootstrap_delta

DELTA_METRICS = ("P@1", "R@10", "MRR@10", "nDCG@10")
CHART_METRICS = ("P@1", "MRR@10", "nDCG@10")

# Categorical slots 1-8 of the reference palette, in fixed order (validated: adjacent
# CVD ΔE ≥ 8.4, normal-vision ΔE ≥ 15). Series color follows the system, never its rank.
SERIES = ("#2a78d6", "#eb6834", "#1baf7a", "#eda100", "#e87ba4", "#008300", "#6250d6", "#e34948")
SURFACE, INK, INK_2, GRID = "#fcfcfb", "#0b0b0b", "#52514e", "#e1e0dc"


class SystemSummary(BaseModel):
    name: str
    label: str
    metrics: dict[str, float]
    ci: dict[str, tuple[float, float]]
    latency_p50_ms: float
    latency_p95_ms: float


class DeltaSummary(BaseModel):
    system: str
    label: str
    metrics: dict[str, tuple[float, float, float]]  # metric → (delta, lo, hi)


class Summary(BaseModel):
    baseline: str
    baseline_label: str
    n_queries: int
    systems: list[SystemSummary]
    deltas: list[DeltaSummary]


def summarize(
    result: BenchmarkResult, *, baseline: str = "dense", n_resamples: int = 2000, seed: int = 0
) -> Summary:
    names = [s.spec.name for s in result.systems]
    if baseline not in names:
        raise ValueError(f"baseline {baseline!r} is not among the systems: {names}")

    scored = {s.spec.name: evaluate_run(s.ranking, result.qrels) for s in result.systems}
    base = scored[baseline]
    systems: list[SystemSummary] = []
    deltas: list[DeltaSummary] = []
    for s in result.systems:
        per_query = scored[s.spec.name]
        cis = {
            m: bootstrap_ci(per_query.values[m], n_resamples=n_resamples, seed=seed)
            for m in METRICS
        }
        latencies = np.asarray(list(s.latency_ms.values()), dtype=np.float64)
        systems.append(
            SystemSummary(
                name=s.spec.name,
                label=s.spec.label,
                metrics={m: cis[m][0] for m in METRICS},
                ci={m: (cis[m][1], cis[m][2]) for m in METRICS},
                latency_p50_ms=float(np.percentile(latencies, 50)),
                latency_p95_ms=float(np.percentile(latencies, 95)),
            )
        )
        if s.spec.name != baseline:
            deltas.append(
                DeltaSummary(
                    system=s.spec.name,
                    label=s.spec.label,
                    metrics={
                        m: paired_bootstrap_delta(
                            per_query.values[m],
                            base.values[m],
                            n_resamples=n_resamples,
                            seed=seed,
                        )
                        for m in DELTA_METRICS
                    },
                )
            )
    baseline_label = next(s.label for s in systems if s.name == baseline)
    return Summary(
        baseline=baseline,
        baseline_label=baseline_label,
        n_queries=len(base.query_ids),
        systems=systems,
        deltas=deltas,
    )


def _ms(value: float) -> str:
    return f"{value:.1f}" if value < 10 else f"{value:,.0f}"


def _verdict(lo: float, hi: float) -> str:
    if lo > 0:
        return " ✓"
    return " ✗" if hi < 0 else ""


def render_markdown(result: BenchmarkResult, summary: Summary) -> str:
    best = {m: max(s.metrics[m] for s in summary.systems) for m in METRICS}

    def cell(s: SystemSummary, metric: str, *, with_ci: bool = False) -> str:
        text = f"{s.metrics[metric]:.3f}"
        if s.metrics[metric] == best[metric]:
            text = f"**{text}**"
        if with_ci:
            lo, hi = s.ci[metric]
            text += f" [{lo:.3f}, {hi:.3f}]"
        return text

    lines = [
        f"# Benchmark: hybrid vs naive RAG on BEIR/{result.dataset}",
        "",
        "_Generated by `hybrid-rag-bench`; do not edit by hand._",
        "",
        f"- **Corpus:** {result.n_docs:,} documents, ingested through the production pipeline "
        "(parse → chunk → contextualize → index)",
        f"- **Queries:** {summary.n_queries} (test split, document-level relevance judgments)",
        f"- **Embedder:** `{result.embedding_model}` · **BM25:** Okapi, k1=1.2, b=0.75 · "
        "**fusion:** RRF, k=60",
        f"- **Archive SHA-256:** `{result.dataset_sha256 or 'n/a'}`",
        "",
        "## Ranking quality",
        "",
        "| System | P@1 | P@5 | P@10 | R@10 | MRR@10 | nDCG@10 [95% CI] | p50 ms | p95 ms |",
        "|---|---:|---:|---:|---:|---:|---:|---:|---:|",
    ]
    for s in summary.systems:
        lines.append(
            f"| {s.label} | {cell(s, 'P@1')} | {cell(s, 'P@5')} | {cell(s, 'P@10')} | "
            f"{cell(s, 'R@10')} | {cell(s, 'MRR@10')} | {cell(s, 'nDCG@10', with_ci=True)} | "
            f"{_ms(s.latency_p50_ms)} | {_ms(s.latency_p95_ms)} |"
        )

    lines += [
        "",
        f"## Paired difference vs {summary.baseline_label}",
        "",
        "Per-query differences, bootstrap 95% CI over queries (2,000 resamples). "
        "✓ = interval entirely above 0 · ✗ = entirely below 0 · blank = inconclusive.",
        "",
        "| System | " + " | ".join(f"Δ{m}" for m in DELTA_METRICS) + " |",
        "|---|" + "---:|" * len(DELTA_METRICS),
    ]
    for d in summary.deltas:
        cells = []
        for m in DELTA_METRICS:
            delta, lo, hi = d.metrics[m]
            cells.append(f"{delta:+.3f} [{lo:+.3f}, {hi:+.3f}]{_verdict(lo, hi)}")
        lines.append(f"| {d.label} | " + " | ".join(cells) + " |")

    lines += [
        "",
        "## Notes",
        "",
        "- Metrics are computed per document: a document's rank is its best chunk's rank. "
        "P@k divides by k, so with ~1 relevant document per query the ceiling of P@10 is ≈0.1; "
        "P@1, R@10, MRR@10 and nDCG@10 are the discriminating columns.",
        "- Latency is the retrieval call only (query embedding, search, fusion, rerank), measured "
        "sequentially on CPU after an untimed warm-up; it is hardware-dependent.",
        "- Reranking sees the fused top-30 chunks and returns the top 20 chunks, "
        "collapsed to the top 10 documents.",
    ]
    return "\n".join(lines) + "\n"


def render_chart(result: BenchmarkResult, summary: Summary, path: Path) -> None:
    try:
        import matplotlib

        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
    except ImportError as exc:  # pragma: no cover - depends on the optional group
        raise ImportError("charts need matplotlib: uv run --group bench hybrid-rag-bench") from exc

    systems = summary.systems
    if len(systems) > len(SERIES):
        raise ValueError(f"at most {len(SERIES)} systems fit the categorical palette")
    colors = [SERIES[i] for i in range(len(systems))]
    labels = [s.label.replace(" (", "\n(") for s in systems]
    ypos = np.arange(len(systems))

    fig, axes = plt.subplots(
        1, len(CHART_METRICS) + 1, figsize=(15, 0.62 * len(systems) + 2.4), sharey=True
    )
    fig.patch.set_facecolor(SURFACE)
    for ax in axes:
        ax.set_facecolor(SURFACE)
        for side in ("top", "right", "left"):
            ax.spines[side].set_visible(False)
        ax.spines["bottom"].set_color(GRID)
        ax.tick_params(axis="both", colors=INK_2, length=0, labelsize=8.5)
        ax.xaxis.grid(True, color=GRID, linewidth=0.8)
        ax.set_axisbelow(True)

    for ax, metric in zip(axes, CHART_METRICS, strict=False):
        means = np.array([s.metrics[metric] for s in systems])
        lows = np.array([s.ci[metric][0] for s in systems])
        highs = np.array([s.ci[metric][1] for s in systems])
        ax.barh(ypos, means, height=0.58, color=colors, edgecolor=SURFACE, linewidth=2)
        ax.errorbar(
            means,
            ypos,
            xerr=[means - lows, highs - means],
            fmt="none",
            ecolor=INK_2,
            elinewidth=1.1,
        )
        ax.set_xlim(0, min(1.0, float(highs.max()) * 1.22))
        for y, mean, high in zip(ypos, means, highs, strict=True):
            ax.text(high + 0.008, y, f"{mean:.3f}", va="center", fontsize=8.5, color=INK)
        ax.set_title(f"{metric}  ·  higher is better", loc="left", fontsize=10, color=INK)

    ax = axes[-1]
    p50 = np.array([s.latency_p50_ms for s in systems])
    floor = float(p50.min()) / 4
    ax.set_xscale("log")
    ax.barh(
        ypos, p50 - floor, left=floor, height=0.58, color=colors, edgecolor=SURFACE, linewidth=2
    )
    ax.set_xlim(floor, float(p50.max()) * 6)
    for y, value in zip(ypos, p50, strict=True):
        ax.text(value * 1.15, y, f"{_ms(value)} ms", va="center", fontsize=8.5, color=INK)
    ax.set_title("p50 latency  ·  lower is better (log)", loc="left", fontsize=10, color=INK)

    axes[0].set_yticks(ypos, labels)
    axes[0].tick_params(axis="y", labelcolor=INK, labelsize=9)
    axes[0].invert_yaxis()
    fig.suptitle(
        f"Hybrid vs naive RAG on BEIR/{result.dataset}",
        x=0.01,
        ha="left",
        fontsize=13,
        fontweight="bold",
        color=INK,
    )
    fig.text(
        0.01,
        0.905,
        f"{summary.n_queries} queries · {result.n_docs:,} documents · "
        "bars: mean with 95% bootstrap CI over queries",
        fontsize=9,
        color=INK_2,
    )
    fig.tight_layout(rect=(0, 0, 1, 0.9))
    fig.savefig(path, dpi=200, facecolor=SURFACE)
    plt.close(fig)
